function remaining(state, boardId, now) {
 if (!boardId || state.fieldBoardId !== boardId || !Number.isFinite(state.fieldOpenedAt) || state.fieldOpenedAt <= 0) return 0;
 return Math.ceil(Math.min(DURATION_MS, Math.max(0, state.fieldOpenedAt + DURATION_MS - now)) / 1000);
}
function warning(name, seconds, index=0) {
 return `@${name} ${seconds} ${seconds === 1 ? 'SECOND' : 'SECONDS'} ${INSULTS[index % INSULTS.length]}`;
}
