'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const H = require('./lib/browser-harness');
(async () => {
  const server = await H.startServer({ port: 19867 }); let browser;
  try {
    browser = await chromium.launch(H.launchOptions());
    const login = await server.api('POST', '/api/auth/gm/login', { password: 'browser-gm-pass' });
    const gmContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await gmContext.addInitScript(token => { sessionStorage.setItem('asoc_gm_token', token); localStorage.setItem('asoc_master_token', token); }, login.data.token);
    const gm = await gmContext.newPage(), errors = [];
    gm.on('pageerror', error => errors.push(error.message));
    await gm.goto(server.base + '/index.html');
    await gm.waitForFunction(() => App.roomCode === 'MASTER' && App.mode === 'multiplayer');
    const heroContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const hero = await H.openHeroPage(heroContext, server, await H.heroToken(server, 'DM Parity Hero'));
    hero.on('pageerror', error => errors.push(error.message));
    const heroId = await hero.evaluate(() => PlayerApp.playerId);
    await gm.evaluate(id => { GMDirectMessages.setOpen(true); GMDirectMessages.open(id); }, heroId);
    await gm.locator('[data-gm-dm-input]').waitFor();
    await gm.locator('[data-gm-dm-input]').fill('PRIVATE parity fixture');
    await gm.locator('[data-gm-dm-input]').press('Enter');
    await gm.getByText('PRIVATE parity fixture', { exact: true }).waitFor();
    await hero.evaluate(() => DirectMessages.open('__GM__'));
    await hero.locator('.dmx-msg p').filter({ hasText: 'PRIVATE parity fixture' }).waitFor();
    for (const [view, host] of [[gm, true], [hero, false]]) {
      const prefix = host ? 'gm-dm' : 'dmx';
      const root = host ? '#gm-dm-console' : '#direct-messages';
      const message = view.locator(`${root} ${host ? '.gm-dm-msg' : '.dmx-msg'}`).filter({ hasText: 'PRIVATE parity fixture' }).first();
      await message.hover();
      await message.locator(`[data-${prefix}-reaction-open]`).last().click();
      const picker = view.getByRole('dialog', { name: 'Private message reactions', exact: true });
      await picker.waitFor();
      assert.equal(await picker.locator('[data-emoji]').count(), await view.evaluate(host => {
        const div = document.createElement('div');
        if (host) App.renderGMEmojiPickers(null, div); else PlayerApp.renderChatEmojiPickers(null, div);
        return div.querySelectorAll('[data-emoji]').length;
      }, host), 'DM catalog is identical to the real general-chat catalog');
      const bounds = await picker.boundingBox();
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= (host ? 1440 : 390), 'floating picker stays in viewport');
      await picker.locator(host ? '.gm-emoji-edit-toggle' : '.chat-emoji-edit-toggle').click();
      await picker.locator('[data-favorite-slot="0"]').click();
      await picker.locator('[data-emoji="👀"]').last().click();
      await picker.locator(host ? '.gm-emoji-edit-toggle' : '.chat-emoji-edit-toggle').click();
      assert.equal(await view.evaluate(host => (host ? App.loadGMEmojiFavorites() : PlayerApp.loadChatEmojiFavorites())[0], host), '👀', 'DM and general chat share the same saved shortcuts');
      await picker.locator('[data-emoji="🔥"]').last().click();
      assert.equal(await picker.count(), 0, 'selection always closes picker');
      await message.locator(`[data-${prefix}-react="🔥"]`).waitFor();
      await message.hover(); await message.locator(`[data-${prefix}-reaction-open]`).last().click();
      await view.keyboard.press('Escape');
      assert.equal(await view.locator('.dm-chat-picker').count(), 0, 'Escape closes picker without closing DM');
      assert.equal(await view.locator(root).isVisible(), true);
      await message.hover(); await message.locator(`[data-${prefix}-reaction-open]`).last().click();
      await view.locator(`${root} ${host ? '[data-gm-dm-input]' : '#dmx-input'}`).click();
      assert.equal(await view.locator('.dm-chat-picker').count(), 0, 'outside click closes picker');
      await view.locator(`[data-${prefix}-attach]`).click();
      const actual = await view.locator(`${root} .${prefix}-attachment-menu>button`).allTextContents();
      const expected = await view.locator(host ? '[data-gm-attachment]' : '[data-chat-attachment]').allTextContents();
      assert.deepEqual(actual, expected, 'all five attachment options exactly clone general-chat labels/order/icons');
      await view.locator(`[data-${prefix}-poll]`).click();
      const poll = view.locator(`[data-${prefix}-poll-maker]`);
      assert.deepEqual(await poll.locator('[name="duration"] option').allTextContents(), await view.locator(host ? '#gm-poll-duration option' : '#chat-poll-duration option').allTextContents());
      await poll.locator('[name="question"]').fill(host ? 'GM private poll' : 'Hero private poll');
      await poll.locator('[name="option"]').nth(0).fill('Yes'); await poll.locator('[name="option"]').nth(1).fill('No');
      await poll.locator('[name="duration"]').selectOption('120');
      await poll.getByRole('button', { name: 'CREATE POLL', exact: true }).click();
      await view.locator(`${root} ${host ? '.gm-dm-poll' : '.dmx-poll'}`).filter({ hasText: host ? 'GM private poll' : 'Hero private poll' }).waitFor();
      const input = view.locator(host ? '[data-gm-dm-input]' : '#dmx-input');
      await input.fill('draft survives ');
      await view.waitForTimeout(650); // Respect the real private-send rate limit.
      await view.locator(`[data-${prefix}-emoji]`).click();
      const emojiPicker = view.getByRole('dialog', { name: 'Private message emojis', exact: true });
      await emojiPicker.locator('[data-emoji="😂"]').last().click();
      assert.equal(host ? await input.textContent() : await input.inputValue(), 'draft survives 😂');
      await input.press('Enter');
      await view.locator(`${root} ${host ? '.gm-dm-msg' : '.dmx-msg'}.mine p`).filter({ hasText: 'draft survives 😂' }).waitFor();
      await input.fill(':hear');
      await view.locator(`${root} .esc-picker:not([hidden])`).waitFor();
      await input.press('Enter');
      assert.ok((host ? await input.textContent() : await input.inputValue()).length > 0);
      assert.equal((host ? await input.textContent() : await input.inputValue()).includes(':hear'), false, 'general-chat shortcode autocomplete is available in DM');
      await input.fill('');
    }
    assert.equal(await gm.evaluate(() => App.chatMessages.some(m => /PRIVATE parity|private poll|draft survives/.test(m.text))), false, 'private operations never enter public GM chat');
    assert.equal(await hero.evaluate(() => PlayerApp.chatMessages.some(m => /PRIVATE parity|private poll|draft survives/.test(m.text))), false, 'private operations never enter public player chat');
    const editable = gm.locator('.gm-dm-msg.mine').filter({ hasText: 'draft survives 😂' }).first();
    await editable.hover(); await editable.locator('[data-gm-dm-edit]').click();
    await gm.locator('[data-gm-dm-input]').fill('edited privately'); await gm.locator('[data-gm-dm-input]').press('Enter');
    await hero.locator('.dmx-msg p').filter({ hasText: 'edited privately' }).waitFor();
    const own = hero.locator('.dmx-msg.mine').filter({ hasText: 'draft survives 😂' }).first();
    await own.hover(); await own.locator('[data-dmx-delete]').click();
    await hero.locator('.dmx-deleted').waitFor();
    const gmEdited = gm.locator('.gm-dm-msg.mine').filter({ hasText: 'edited privately' }).first();
    await gmEdited.hover(); await gmEdited.locator('[data-gm-dm-delete]').click();
    await gm.locator('.gm-dm-deleted').waitFor();
    const shots = path.join(H.ROOT, '.scratch', 'dm-parity'); fs.mkdirSync(shots, { recursive: true });
    for (const [view, prefix, label] of [[gm, 'gm-dm', 'gm'], [hero, 'dmx', 'player-mobile']]) {
      const message = view.locator(prefix === 'gm-dm' ? '.gm-dm-msg' : '.dmx-msg').filter({ hasText: 'PRIVATE parity fixture' }).first();
      await message.hover(); await message.locator(`[data-${prefix}-reaction-open]`).last().click();
      await view.getByRole('dialog', { name: 'Private message reactions', exact: true }).waitFor();
      await view.waitForTimeout(250);
      assert.equal(await view.locator('.dm-chat-picker').isVisible(), true, 'picker survives late read/list updates and scrolling');
      await view.screenshot({ path: path.join(shots, `${label}.png`) });
    }
    assert.deepEqual(errors, []);
    console.log('PASS DM/general parity: exact emoji catalogs and attachment menus, real GM/player reactions and polls, portal bounds, select/Escape/outside dismiss, preserved drafts, no public leaks');
  } finally { await browser?.close(); await server.stop(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
