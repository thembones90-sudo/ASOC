'use strict';
const assert=require('node:assert/strict');
const p=require('../mudpits');
let s=p.newDuel({id:'m1',contestants:[{id:'gm',name:'GM'},{id:'p2',name:'P2'}],now:0});
assert.equal(p.submit(s,'gm','first sentence',1).ok,true);
assert.equal(p.view(s,'p2').entries,null,'other contestant cannot see sealed text');
assert.equal(p.submit(s,'p2','second sentence',2).revealed,true);
assert.equal(p.view(s,'spectator').entries[0].text,'first sentence');
assert.equal(p.castVote(s,'gm','p2').ok,false,'contestants cannot vote');
assert.equal(p.tick(s,5002).events.includes('voting'),true);
assert.equal(p.castVote(s,'v1','gm',3).ok,true);
assert.equal(p.castVote(s,'v1','p2',3).ok,false,'duplicate vote rejected');
p.tick(s,5003); p.tick(s,65003);
assert.equal(s.winnerId,'gm');
let voidPit=p.newDuel({id:'m2',contestants:['a','b'],now:0});
p.submit(voidPit,'a','only one',1); p.tick(voidPit,90000); p.tick(voidPit,95000); p.tick(voidPit,155000);
assert.equal(voidPit.winnerId,null,'forfeit/void never awards a winner');
assert.match(p.submit(p.newDuel({id:'m3',contestants:['a','b'],now:0}),'a','x'.repeat(251),1).error,/CHARACTERS/);
const late=p.newDuel({id:'late',contestants:['a','b'],now:1});
assert.equal(p.submit(late,'a','Too late',late.writeDeadline).ok,false);
assert.equal(p.saveDraft(late,'a','Too late',late.writeDeadline).ok,false);
const tie=p.newDuel({id:'tie',contestants:['a','b'],now:1});
p.submit(tie,'a','One sentence',2);p.submit(tie,'b','Another sentence',3);
p.tick(tie,tie.readDeadline);p.castVote(tie,'v1','a',tie.readDeadline+1);p.castVote(tie,'v2','b',tie.readDeadline+2);
assert.equal(p.castVote(tie,'v3','a',tie.voteDeadline).ok,false);
p.tick(tie,tie.voteDeadline);assert.equal(tie.winnerId,null);assert.equal(tie.tie,true);
assert.deepEqual(p.normalizeState(JSON.parse(JSON.stringify(tie))).counts,{a:1,b:1},'verdict tallies survive restart');
assert.equal(p.WRITE_MS,90000);assert.equal(p.READ_MS,5000);assert.equal(p.VOTE_MS,60000);
console.log('PASS Mud Pits privacy, deadlines, vote, duplicate, tie and void rules');
