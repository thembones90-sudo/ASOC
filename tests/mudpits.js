'use strict';
const assert=require('node:assert/strict');
const p=require('../mudpits');
let s=p.newDuel({id:'m1',contestants:[{id:'gm',name:'GM'},{id:'p2',name:'P2'}],now:0});
assert.equal(p.submit(s,'gm','first sentence',1).ok,true);
assert.equal(p.view(s,'p2').entries,null,'other contestant cannot see sealed text');
assert.equal(p.submit(s,'p2','second sentence',2).revealed,true);
assert.equal(p.view(s,'spectator').entries[0].text,'first sentence');
assert.equal(p.castVote(s,'gm','p2').ok,false,'contestants cannot vote');
assert.equal(p.tick(s,5002).events.includes('voting'),true);
assert.equal(p.castVote(s,'v1','gm',3).ok,true);
assert.equal(p.castVote(s,'v1','p2',3).ok,false,'duplicate vote rejected');
p.tick(s,5003); p.tick(s,65003);
assert.equal(s.winnerId,'gm');
let voidPit=p.newDuel({id:'m2',contestants:['a','b'],now:0});
p.submit(voidPit,'a','only one',1); p.tick(voidPit,90000); p.tick(voidPit,95000); p.tick(voidPit,155000);
assert.equal(voidPit.winnerId,null,'forfeit/void never awards a winner');
assert.match(p.submit(p.newDuel({id:'m3',contestants:['a','b'],now:0}),'a','x'.repeat(251)).error,/CHARACTERS/);
console.log('PASS Mud Pits privacy, timer, vote, duplicate and void rules');
