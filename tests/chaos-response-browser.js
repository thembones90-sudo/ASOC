process.chdir('A:\\ASOC ENGINE');
const { chromium }=require('playwright');
const fs=require('fs'),path=require('path'),assert=require('assert');
(async()=>{
 const fixture=path.resolve('.scratch/chaos-response-fixture.html');
 fs.writeFileSync(fixture,'<html><head><meta charset="utf-8"><link rel="stylesheet" href="../css/chaos.css"></head><body><script>window.sent=[];window.canSend=false;window.PlayerApp={playerId:"sissy",send(m){if(!window.canSend)return false;window.sent.push(m);return true;}};</script><script src="../js/chaos.js"></script></body></html>');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:970,height:650}});
 await page.goto('file:///'+fixture.replace(/\\/g,'/'));
 const setup=()=>page.evaluate(()=>window.ChaosGame.onState({chaos:{sissy:{id:'offer-1',playerId:'sissy',status:'offered',target:50,coins:5,expiresAt:Date.now()+30000,serverNow:Date.now()}}}));
 await setup();
 await page.locator('[data-chaos-accept]').click();
 assert((await page.locator('[data-chaos-response-note]').innerText()).includes('CONNECTION LOST'),'offline send must not lock button');
 assert(await page.locator('[data-chaos-accept]').isEnabled(),'offline retry enabled');
 await page.evaluate(()=>window.canSend=true);
 await page.locator('[data-chaos-accept]').click();
 assert.equal(await page.locator('[data-chaos-accept]').isDisabled(),true);
 assert.equal(await page.evaluate(()=>window.sent.length),1);
 assert.equal(await page.evaluate(()=>window.sent[0].chaosEntryId),'offer-1');
 await page.locator('[data-chaos-accept]').click({force:true});
 assert.equal(await page.evaluate(()=>window.sent.length),1,'repeat click must not duplicate');
 await page.evaluate(()=>window.ChaosGame.onMessage({type:'chaos:responseError',chaosEntryId:'offer-1',error:'RETRY PLEASE'}));
 assert(await page.locator('[data-chaos-accept]').isEnabled(),'negative ACK unlocks');
 assert((await page.locator('[data-chaos-response-note]').innerText()).includes('RETRY PLEASE'));
 await page.locator('[data-chaos-accept]').click();
 assert.equal(await page.evaluate(()=>window.sent.length),2);
 await page.evaluate(()=>window.ChaosGame.onMessage({type:'chaos:response',playerId:'sissy',chaosEntryId:'offer-1',accepted:true,rollEndsAt:Date.now()+55000}));
 assert(await page.locator('[data-chaos-roll]').isVisible(),'positive ACK must show roll');
 console.log('CHAOS_RESPONSE_BROWSER_PASS: offline, send, duplicate suppression, reject and retry, successful ack');
 await browser.close();
})().catch(e=>{console.error('CHAOS_RESPONSE_BROWSER_FAIL',e.stack);process.exit(1)});
